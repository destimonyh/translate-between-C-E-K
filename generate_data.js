// ---------- 编译 ----------
function build(list, domain) {
  return list.map((e) => {
    const [zh, en, level, note, koRom, koMean] = e;
    const hasKo = !!koRom && !!koMean;
    return {
      zh, en, domain, level, note,
      koRom: koRom || '需验证',
      koMean: koMean || '需验证',
      conf: hasKo ? 'verified' : 'needs-check',
    };
  });
}

